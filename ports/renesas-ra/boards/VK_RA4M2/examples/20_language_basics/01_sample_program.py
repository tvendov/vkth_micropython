# Пример: Примерна MicroPython програма за VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.

from machine import Pin  # Импортираме класа Pin, чрез който управляваме GPIO пиновете.
import time  # Импортираме модула time, за да правим закъснения между действията.

LED_PIN_NAME = "LED1"  # Записваме board alias-а на потребителския светодиод в константа.
LED_OFF_LEVEL = 1  # При тази платка LED1 е active-low, затова логическа 1 означава изгасен LED.
LED_ON_LEVEL = 0  # При тази платка логическа 0 означава светнат LED.

led = Pin(LED_PIN_NAME, Pin.OUT, value=LED_OFF_LEVEL)  # Създаваме изходен обект за LED1 и започваме с изгасен LED.

print("=== Примерна програма за VK_RA4M2 ===")  # Показваме заглавие, за да се вижда кой пример работи.
print("Ще премигнем LED1 три пъти.")  # Обясняваме на потребителя какво ще направи програмата.

for blink_index in range(3):  # Обхождаме три последователни мигания с for цикъл.
    print("Мигане номер:", blink_index + 1)  # Печатаме поредния номер на мигането за по-лесно следене.
    led.value(LED_ON_LEVEL)  # Светваме LED1 като подадем активното за платката ниво.
    time.sleep_ms(300)  # Изчакваме 300 милисекунди, за да се вижда светването.
    led.value(LED_OFF_LEVEL)  # Гасим LED1, за да завършим едно мигане.
    time.sleep_ms(300)  # Изчакваме още 300 милисекунди преди следващото мигане.

print("Примерът приключи успешно.")  # Съобщаваме, че програмата е завършила.
