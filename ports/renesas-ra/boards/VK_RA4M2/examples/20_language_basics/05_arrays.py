# Пример: Масиви и таблици в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.

from array import array  # Импортираме array, за да покажем по-компактен числов масив от list.

adc_samples = [1200, 1215, 1198, 1222]  # Това е обикновен list, който играе роля на масив от измервания.
led_table = [["LED1", "P204"], ["SW1", "P400"]]  # Това е вложен масив, тоест таблица от редове и колони.
pwm_duty_values = array("H", [0, 16384, 32768, 49152, 65535])  # Тук пазим 16-битови стойности в компактен масив.
raw_bytes = bytearray([0x10, 0x20, 0x30, 0x40])  # bytearray е удобен за сурови байтове и комуникационни буфери.

print("=== Масиви и таблици ===")  # Печатаме заглавие на примера.
print("Първа ADC проба:", adc_samples[0])  # Достъпваме първия елемент в list по индекс.

adc_samples[1] = 1300  # Променяме втория елемент, за да покажем че list е изменяем.
print("Променен списък с ADC проби:", adc_samples)  # Печатаме целия list след промяната.

print("Втори ред от таблицата:", led_table[1])  # Вземаме втория ред от двумерната таблица.
print("Пинът на LED1 е", led_table[0][1])  # Достъпваме елемент от ред и колона в двумерен масив.
print("PWM стойности:", list(pwm_duty_values))  # Преобразуваме array към list само за удобно печатане.

raw_bytes[2] = 0x55  # Променяме третия байт в bytearray.
print("Буферът с байтове е", list(raw_bytes))  # Печатаме bytearray като list от числа.

print("Примерът за масиви приключи.")  # Завършваме примера.
