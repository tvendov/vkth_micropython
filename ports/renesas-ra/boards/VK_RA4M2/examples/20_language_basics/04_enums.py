# Пример: Енъми в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.

from micropython import const  # Импортираме const, за да правим именувани константи като прост MicroPython еквивалент на enum.

STATE_OFF = const(0)  # Тази константа означава състояние "изключено".
STATE_ON = const(1)  # Тази константа означава състояние "включено".
STATE_BLINK = const(2)  # Тази константа означава състояние "мигане".

MODE_NAMES = {STATE_OFF: "OFF", STATE_ON: "ON", STATE_BLINK: "BLINK"}  # Тук правим таблица, която превежда числото до четимо име.


class LedMode:  # Дефинираме клас само като контейнер за групирани константи.
    OFF = const(0)  # Това е именувана константа за изключен LED.
    ON = const(1)  # Това е именувана константа за включен LED.
    BLINK = const(2)  # Това е именувана константа за мигащ LED.


selected_mode = STATE_BLINK  # Избираме едно от enum-подобните състояния за демонстрацията.

print("=== Енъми в MicroPython ===")  # Печатаме заглавие на примера.
print("Константа STATE_BLINK =", selected_mode)  # Показваме числовата стойност на избраното състояние.
print("Четимото име е", MODE_NAMES[selected_mode])  # Показваме как таблицата превръща числото обратно в име.

if selected_mode == LedMode.OFF:  # Проверяваме дали избраният режим е OFF.
    print("LED трябва да е изключен.")  # Този ред би се изпълнил при OFF.
elif selected_mode == LedMode.ON:  # Проверяваме дали избраният режим е ON.
    print("LED трябва да е включен.")  # Този ред би се изпълнил при ON.
else:  # Ако не е OFF и не е ON, остава BLINK за нашия прост пример.
    print("LED трябва да мига.")  # Показваме как enum стойността управлява логиката.

print("Примерът за енъми приключи.")  # Завършваме примера с финално съобщение.
