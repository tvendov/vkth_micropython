# Пример: Еквиваленти на указатели в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.

import machine  # Импортираме machine, за да покажем че портът има ниско ниво достъп като mem32.

adc_list = [100, 200, 300]  # Създаваме изменяем обект, който ще играе ролята на споделени данни.
alias_list = adc_list  # Тук не се копира list, а и двете имена сочат към един и същ обект.
alias_list[1] = 999  # Промяната през второто име се вижда и през първото име.

tx_buffer = bytearray([1, 2, 3, 4])  # bytearray е полезен за буфери, които се редактират "на място".
tx_view = memoryview(tx_buffer)  # memoryview дава прозорец към същите байтове без копиране.
tx_view[2] = 77  # Промяната през memoryview променя и оригиналния буфер.

print("=== Еквиваленти на указатели ===")  # Печатаме заглавие на примера.
print("Оригиналният list след промяна през alias е", adc_list)  # Показваме ефекта на споделена референция.
print("Буферът след промяна през memoryview е", list(tx_buffer))  # Показваме ефекта на memoryview върху същите данни.

print("Има ли machine.mem32:", hasattr(machine, "mem32"))  # Проверяваме дали портът предлага директен достъп до регистри.
print("Бележка: machine.mem8/mem16/mem32 са за напреднали и тук не пишем по реални регистри.")  # Даваме безопасна бележка вместо рисков хардуерен достъп.

print("Примерът за еквиваленти на указатели приключи.")  # Завършваме примера.
