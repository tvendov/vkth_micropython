# Пример: Оператори, условия и цикли в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.

left_value = 7  # Първата числова променлива участва в аритметичните операции.
right_value = 3  # Втората числова променлива е вторият операнд.

sum_value = left_value + right_value  # Събираме двете стойности с оператора плюс.
diff_value = left_value - right_value  # Изваждаме двете стойности с оператора минус.
product_value = left_value * right_value  # Умножаваме стойностите със звездичка.
division_value = left_value / right_value  # Делим стойностите с наклонена черта и получаваме число с плаваща запетая.
mod_value = left_value % right_value  # Намираме остатъка от деление с процента.

is_left_bigger = left_value > right_value  # Сравняваме двете стойности и получаваме булев резултат.
is_equal = left_value == right_value  # Проверяваме дали стойностите са равни.
logic_result = is_left_bigger and (not is_equal)  # Комбинираме логически оператори and и not.

print("=== Оператори ===")  # Показваме заглавие за частта с операторите.
print("Сума:", sum_value)  # Печатаме резултата от събирането.
print("Разлика:", diff_value)  # Печатаме резултата от изваждането.
print("Произведение:", product_value)  # Печатаме резултата от умножението.
print("Деление:", division_value)  # Печатаме резултата от делението.
print("Остатък:", mod_value)  # Печатаме остатъка от делението.
print("left_value > right_value:", is_left_bigger)  # Печатаме резултата от сравнението.
print("left_value == right_value:", is_equal)  # Печатаме резултата от проверката за равенство.
print("Логически резултат:", logic_result)  # Печатаме крайния логически резултат.

print("=== if / elif / else ===")  # Показваме заглавие за условните конструкции.
if left_value < right_value:  # Проверяваме първото условие.
    print("Лявата стойност е по-малка.")  # Този ред би се изпълнил, ако първото условие е вярно.
elif left_value == right_value:  # Ако първото условие е невярно, проверяваме второто.
    print("Двете стойности са равни.")  # Този ред би се изпълнил при равенство.
else:  # Ако нито едно от горните условия не е изпълнено, влизаме в else клона.
    print("Лявата стойност е по-голяма.")  # Тук попадаме с текущите примерни стойности.

print("=== for цикъл ===")  # Показваме заглавие за for цикъла.
for index in range(3):  # Изпълняваме цикъл точно три пъти.
    print("for iteration:", index)  # Печатаме текущата стойност на брояча.

print("=== while цикъл ===")  # Показваме заглавие за while цикъла.
counter = 0  # Създаваме брояч за while цикъла.
while counter < 3:  # Повтаряме докато броячът е по-малък от три.
    print("while iteration:", counter)  # Печатаме текущата стойност на брояча.
    counter = counter + 1  # Увеличаваме брояча, за да не останем в безкраен цикъл.

print("=== do-while еквивалент ===")  # Показваме как в Python имитираме do-while.
attempt = 0  # Създаваме брояч за демонстрацията.
while True:  # Влизаме в безкраен цикъл, който ще прекъснем с break.
    print("do-while iteration:", attempt)  # Печатаме текущата стойност, като това винаги се случва поне веднъж.
    attempt = attempt + 1  # Увеличаваме брояча след изпълнението на тялото.
    if attempt >= 2:  # Проверяваме условието за прекратяване след тялото на цикъла.
        break  # Напускаме цикъла, което прави конструкцията еквивалент на do-while.

print("Примерът приключи.")  # Показваме финално съобщение.
