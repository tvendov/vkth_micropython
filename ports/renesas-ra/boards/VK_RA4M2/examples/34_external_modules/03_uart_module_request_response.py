# Пример: Работа с външен UART модул чрез request/response и timeout.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: Командата AT е само пример за текстов протокол; реалният модул може да изисква друг синтаксис.

from machine import UART  # Импортираме UART за сериен обмен с външен модул.
import time  # Импортираме time за timeout логика и кратки паузи.

UART_CHANNEL = 9  # Избираме UART(9), защото е отделен от I2C и TouchPad ресурсите.
UART_BAUD = 115200  # Започваме с масово използвана скорост за модулни интерфейси.
READ_TIMEOUT_MS = 300  # Ограничаваме чакането, за да няма блокиране безкрайно.
REQUEST = b"AT\r\n"  # Подготвяме примерна текстова команда от тип AT.

uart = UART(UART_CHANNEL, UART_BAUD)  # Създаваме UART инстанция с избраните параметри.

print("=== Външен UART модул: request/response ===")  # Печатаме заглавие на примера.
print("Използван UART обект:", uart)  # Показваме избрания канал и конфигурацията му.
print("Команда за изпращане:", REQUEST)  # Показваме каква команда ще предадем.

stale_bytes = uart.any()  # Проверяваме дали има остатъчни байтове от стара сесия.
if stale_bytes:  # Ако в буфера има стари данни:
    dropped = uart.read(stale_bytes)  # Изчистваме буфера преди новата транзакция.
    print("Изчистени стари байтове:", dropped)  # Показваме какво сме изхвърлили.
else:  # Ако буферът е празен:
    print("RX буферът е чист преди новата команда.")  # Потвърждаваме чист старт.

written = uart.write(REQUEST)  # Изпращаме командата към външния модул.
print("Изпратени байтове:", written)  # Печатаме колко байта са предадени.

start_ms = time.ticks_ms()  # Маркираме началото на timeout прозореца.
response = b""  # Подготвяме празен буфер за натрупване на отговора.

while time.ticks_diff(time.ticks_ms(), start_ms) < READ_TIMEOUT_MS:  # Чакаме ограничено време за данни:
    available = uart.any()  # Проверяваме дали вече има получени байтове.
    if available:  # Ако има налични байтове:
        chunk = uart.read(available)  # Четем ги от RX буфера.
        if chunk:  # Ако наистина сме получили валиден обект bytes:
            response += chunk  # Добавяме новия фрагмент към общия отговор.
            break  # Спираме след първия отговор за този прост пример.
    time.sleep_ms(10)  # Отстъпваме кратко време преди следващата проверка.

if response:  # Ако има получен отговор:
    print("Получен отговор:", response)  # Печатаме суровия байтов отговор.
    print("Декодиране с ignore:", response.decode("utf-8", "ignore"))  # Показваме и текстов вариант при текстов протокол.
else:  # Ако няма получен отговор:
    print("Няма отговор в рамките на timeout-а.")  # Печатаме ясен timeout резултат.
    print("Провери TX/RX кръстосването, GND, baud rate и протокола на модула.")  # Даваме най-честите проверки.

print("Примерът за UART module request/response приключи.")  # Завършваме примера.
