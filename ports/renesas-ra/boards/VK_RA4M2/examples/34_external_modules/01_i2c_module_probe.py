# Пример: Работа с външен I2C модул чрез scan, probe и безопасно четене на регистър.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: За външен I2C модул в този курс използваме I2C(1), защото I2C(0) дели P400 със SW1.

from machine import I2C  # Импортираме I2C за работа с външен модул като master.
import time  # Импортираме time за кратки диагностични паузи.

I2C_BUS = 1  # Избираме хардуерния I2C канал 1 върху P100/P101.
I2C_FREQ = 100000  # Започваме консервативно със 100 kHz за първо свързване.
EXPECTED_ADDR = 0x3C  # Това е примерен адрес на често срещан OLED или друг I2C модул.
ID_REGISTER = 0x00  # Това е примерен регистър за probe четене, който трябва да се смени според datasheet-а.

i2c = I2C(I2C_BUS, freq=I2C_FREQ)  # Създаваме I2C master с безопасна начална скорост.

print("=== Външен I2C модул: scan и probe ===")  # Печатаме заглавие на примера.
print("Използван канал:", i2c)  # Показваме активния I2C обект и неговата конфигурация.
print("Очакван адрес:", hex(EXPECTED_ADDR))  # Показваме към кой адрес ще правим целеви probe.

devices = i2c.scan()  # Сканираме шината за всички 7-битови адреси.
hex_devices = [hex(addr) for addr in devices]  # Преобразуваме адресите в по-четим шестнадесетичен вид.
print("Намерени адреси:", hex_devices)  # Печатаме списъка с намерени устройства.

if not devices:  # Ако няма нито едно устройство на шината:
    print("Няма отговор от външен I2C модул.")  # Даваме ясен диагностичен резултат.
    print("Провери GND, VCC, SDA, SCL и pull-up резисторите.")  # Напомняме основните физически проверки.
else:  # Ако има поне едно устройство:
    print("Шината работи и има поне един активен target.")  # Потвърждаваме, че базовата комуникация е жива.

if EXPECTED_ADDR in devices:  # Ако точно очакваният адрес е видим на шината:
    print("Очакваният адрес е намерен.")  # Потвърждаваме, че сме открили правилния модул.
    time.sleep_ms(20)  # Изчакваме кратко преди probe четене.
    try:  # Опитваме контролирано четене на един байт от примерен регистър.
        raw_id = i2c.readfrom_mem(EXPECTED_ADDR, ID_REGISTER, 1)  # Четем един байт от избрания регистър.
        print("Прочетен байт от регистър", hex(ID_REGISTER), "=", list(raw_id))  # Печатаме суровия резултат.
    except OSError as exc:  # Ако модулът не поддържа този регистър или има bus грешка:
        print("Probe четенето се провали:", exc)  # Показваме конкретната грешка за диагностика.
        print("Смени ID_REGISTER според datasheet-а на реалния модул.")  # Насочваме към правилната следваща стъпка.
else:  # Ако адресът не е намерен:
    print("Очакваният адрес не е открит.")  # Поясняваме, че модулът може да е на друг адрес.
    print("Сравни джъмпери, A0/A1/A2 пинове и документацията на модула.")  # Напомняме типичните причини.

print("Примерът за I2C module probe приключи.")  # Завършваме примера.
