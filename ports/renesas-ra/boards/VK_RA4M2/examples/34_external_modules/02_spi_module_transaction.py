# Пример: Работа с външен SPI модул чрез CS рамка и пълен трансфер.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: За loopback тест може временно да свържете MOSI към MISO, но тук примерът е формулиран като шаблон за външен SPI модул.

from machine import SPI, Pin  # Импортираме SPI и Pin за хардуерна SPI връзка и управление на CS.
import time  # Импортираме time за кратки паузи между фазите на транзакцията.

SPI_BAUDRATE = 500000  # Започваме със скромна скорост за първи контакт с нов модул.
SPI_POLARITY = 0  # Полярността трябва да съвпада с datasheet-а на модула.
SPI_PHASE = 0  # Фазата трябва да съвпада с datasheet-а на модула.

cs = Pin("P103", Pin.OUT, value=1)  # Държим CS в неактивно високо ниво преди трансфер.
spi = SPI(0, baudrate=SPI_BAUDRATE, polarity=SPI_POLARITY, phase=SPI_PHASE, bits=8, sck=Pin("P102"), mosi=Pin("P101"), miso=Pin("P100"), cs=cs)  # Създаваме hardware SPI върху валидните пинове.

tx_frame = bytes([0x9F, 0x00, 0x00, 0x00])  # Подготвяме примерна команда плюс три dummy байта за отговор.
rx_frame = bytearray(len(tx_frame))  # Подготвяме приемен буфер със същата дължина.

print("=== Външен SPI модул: framed transaction ===")  # Печатаме заглавие на примера.
print("Използван SPI обект:", spi)  # Показваме текущата конфигурация на шината.
print("CS пинът започва в idle състояние:", cs.value())  # Потвърждаваме, че CS е неактивен.
print("TX frame:", [hex(value) for value in tx_frame])  # Показваме байтовете, които ще изпратим.

cs.value(0)  # Активираме целевия модул чрез CS.
time.sleep_us(5)  # Изчакваме кратко setup време преди обмена.
spi.write_readinto(tx_frame, rx_frame)  # Изпращаме командата и четем едновременно отговора.
time.sleep_us(5)  # Изчакваме кратко hold време след обмена.
cs.value(1)  # Освобождаваме модула чрез CS.

print("RX frame:", [hex(value) for value in rx_frame])  # Печатаме суровия отговор от модула.

if list(rx_frame) == [0x00] * len(rx_frame):  # Ако всичко е нули:
    print("Отговорът е изцяло 0x00.")  # Даваме първа интерпретация на резултата.
    print("Това често значи липсващ модул, грешен mode или грешен wiring.")  # Посочваме типичните причини.
elif list(rx_frame) == [0xFF] * len(rx_frame):  # Ако всичко е 0xFF:
    print("Отговорът е изцяло 0xFF.")  # Даваме втора типична интерпретация.
    print("Това често значи плаваща MISO линия или неактивен target.")  # Посочваме типичните причини.
else:  # Ако има смислени или поне различни байтове:
    print("Има данни за анализ по datasheet.")  # Насочваме към следващата стъпка при реален модул.
    print("Сравни RX frame с очаквания отговор за избраната команда.")  # Подчертаваме нуждата от документация.

print("Примерът за SPI module transaction приключи.")  # Завършваме примера.
