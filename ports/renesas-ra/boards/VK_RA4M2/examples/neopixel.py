# Пример: NeoPixel rainbow cycle върху външен RGB модул.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: P500 тук се използва като удобно малко захранване за единичен NeoPixel модул, не за дълга LED лента.

from machine import Pin  # Импортираме Pin за управление на захранващия и data пина.
import neopixel  # Импортираме neopixel драйвера за timed bitstream към RGB модула.
import time  # Импортираме time за изчакване между цветовете.

POWER_PIN = "P500"  # Избираме P500 като захранващ GPIO за малък външен модул.
DATA_PIN = "P112"  # Избираме P112 като data pin към DIN на NeoPixel-а.
PIXEL_COUNT = 1  # Работим с един NeoPixel модул.
STEP_DELAY_MS = 500  # Изчакваме половин секунда между отделните цветове.

vcc = Pin(POWER_PIN, Pin.OUT, value=1)  # Подаваме логическа единица на P500, за да захраним модула.
np = neopixel.NeoPixel(Pin(DATA_PIN), PIXEL_COUNT)  # Създаваме NeoPixel обект върху data линията.

colors = [  # Подготвяме проста дъгова таблица от цветове с умерена яркост.
    (40, 0, 0),  # Червено.
    (40, 20, 0),  # Оранжево.
    (40, 40, 0),  # Жълто.
    (0, 40, 0),  # Зелено.
    (0, 40, 40),  # Циан.
    (0, 0, 40),  # Синьо.
    (20, 0, 40),  # Виолетово.
    (40, 0, 20),  # Магента.
]  # Завършваме таблицата с цветове.

print("=== NeoPixel rainbow cycle ===")  # Печатаме заглавие на примера.
print("POWER =", POWER_PIN, "DATA =", DATA_PIN, "PIXELS =", PIXEL_COUNT)  # Печатаме използваните пинове и броя пиксели.

try:  # Стартираме безкрайния цветови цикъл с възможност за чисто спиране.
    while True:  # Повтаряме дъгата непрекъснато.
        for color in colors:  # Обхождаме всички предварително зададени цветове.
            np[0] = color  # Зареждаме текущия цвят в първия и единствен пиксел.
            np.write()  # Изпращаме новото RGB състояние към NeoPixel-а.
            time.sleep_ms(STEP_DELAY_MS)  # Изчакваме, за да се вижда цветът достатъчно дълго.
except KeyboardInterrupt:  # Ако потребителят спре примера ръчно:
    np[0] = (0, 0, 0)  # Гасим пиксела преди изход.
    np.write()  # Прилагаме командата за изключване.
    print("NeoPixel примерът беше спрян и пикселът е изгасен.")  # Печатаме чист финал.
