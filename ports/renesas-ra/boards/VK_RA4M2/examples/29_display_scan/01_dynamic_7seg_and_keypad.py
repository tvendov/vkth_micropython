# Пример: Динамична 7-сегментна индикация и матрично сканиране на бутони на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: Този пример изисква външен 2-цифрен 7-сегментен индикатор и матрица от бутони, свързани към указаните пинове.

from machine import Pin  # Импортираме Pin, за да покажем базовото сканиране на външен дисплей и бутони.
import time  # Импортираме time за краткото динамично опресняване.

segment_pins = [Pin(name, Pin.OUT) for name in ("P105", "P104", "P113", "P114", "P115", "P304", "P303")]  # Това са седемте сегмента a..g.
digit_pins = [Pin(name, Pin.OUT) for name in ("P608", "P409")]  # Това са двата общи извода за две цифри.

row_pins = [Pin(name, Pin.OUT) for name in ("P408", "P600")]  # Това са редовете на примерна 2x2 клавиатурна матрица.
col_pins = [Pin(name, Pin.IN, Pin.PULL_UP) for name in ("P301", "P302")]  # Това са колоните на примерната 2x2 клавиатурна матрица.

patterns = {"1": (0, 1, 1, 0, 0, 0, 0), "2": (1, 1, 0, 1, 1, 0, 1)}  # Това са сегментните шаблони за две примерни цифри.

print("=== Динамична индикация и матрично сканиране ===")  # Печатаме заглавие на примера.

for refresh_step in range(10):  # Повтаряме кратък опреснителен цикъл десет пъти.
    for digit_index, symbol in enumerate(("1", "2")):  # Показваме символ 1 на първата цифра и 2 на втората цифра.

        for digit_pin in digit_pins:  # Първо изключваме всички цифри, за да няма ghosting.
            digit_pin.off()  # Изключваме текущата цифра.

        for segment_pin, level in zip(segment_pins, patterns[symbol]):  # Зареждаме нужния сегментен шаблон за текущия символ.
            segment_pin.value(level)  # Настройваме сегмента според шаблона.

        digit_pins[digit_index].on()  # Включваме само текущата цифра за кратко време.
        time.sleep_ms(5)  # Държим цифрата включена кратко, за да се получи динамична индикация.

pressed_keys = []  # Подготвяме списък за натиснати клавиши от матрицата.

for row_index, row_pin in enumerate(row_pins):  # Сканираме всеки ред поотделно.
    for reset_row in row_pins:  # Първо изключваме всички редове.
        reset_row.off()  # Изключваме реда.

    row_pin.on()  # Активираме текущия ред.

    for col_index, col_pin in enumerate(col_pins):  # Проверяваме всяка колона в активния ред.
        if col_pin.value() == 0:  # Ако колоната падне на 0, приемаме че бутонът е натиснат.
            pressed_keys.append((row_index, col_index))  # Записваме координатите на натиснатия бутон.

print("Намерени натиснати бутони:", pressed_keys)  # Печатаме резултата от матричното сканиране.

print("Примерът за 7-сегментен дисплей и матрица приключи.")  # Завършваме примера.
