# Пример: Цифров вход с бутона SW1 на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: В този порт Pin.PULL_UP се поддържа, а Pin.PULL_DOWN не се поддържа.
# Бележка: При SW1 логическа 0 означава натиснат бутон, а логическа 1 означава отпуснат бутон.

from machine import Pin  # Импортираме Pin, за да четем бутона SW1 като цифров вход.
import time  # Импортираме time, за да четем бутона периодично.

BUTTON_PIN_NAME = "SW1"  # Използваме board alias-а на потребителския бутон.

button = Pin(BUTTON_PIN_NAME, Pin.IN, Pin.PULL_UP)  # Настройваме бутона като вход с вътрешен pull-up резистор.

print("=== Цифров вход с SW1 ===")  # Показваме заглавие на примера.
print("Натиснат бутон = логическа 0, отпуснат бутон = логическа 1.")  # Обясняваме как ще тълкуваме стойностите.

for sample_index in range(20):  # Четем бутона 20 пъти, за да не остава примерът безкраен.
    raw_value = button.value()  # Вземаме текущата сурова логическа стойност на входа.
    if raw_value == 0:  # Проверяваме дали бутонът е натиснат.
        print("Проба", sample_index + 1, ": SW1 е натиснат.")  # Печатаме човеко-четимото състояние.
    else:  # Ако стойността не е 0, бутонът се счита за отпуснат.
        print("Проба", sample_index + 1, ": SW1 е отпуснат.")  # Печатаме човеко-четимото състояние.
    time.sleep_ms(200)  # Чакаме 200 ms между пробите, за да може състоянието да се променя видимо.

print("Примерът за цифров вход приключи.")  # Показваме финално съобщение.
