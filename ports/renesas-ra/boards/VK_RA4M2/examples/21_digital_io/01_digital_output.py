# Пример: Цифров изход с LED1 на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: При тази платка LED1 е active-low, което означава че логическа 0 светва LED-а, а логическа 1 го гаси.
# Бележка: Допустимият изходен ток и товароспособността се гледат по хардуерния manual на RA4M2 и схемата на платката.

from machine import Pin  # Импортираме класа Pin, за да използваме LED1 като цифров изход.
import time  # Импортираме time, за да правим видими паузи между смените на логическото ниво.

LED_PIN_NAME = "LED1"  # Използваме board alias-а, за да не се налага да помним P204.
LOGIC_ZERO_LEVEL = 0  # При тази конкретна платка логическа нула светва LED1.
LOGIC_ONE_LEVEL = 1  # При тази конкретна платка логическа единица гаси LED1.

led = Pin(LED_PIN_NAME, Pin.OUT, value=LOGIC_ONE_LEVEL)  # Настройваме LED1 като изход и го оставяме изгасен в началото.

print("=== Цифров изход с LED1 ===")  # Печатаме заглавие на примера.
print("Логическа 0 ще светне LED1, а логическа 1 ще го изгаси.")  # Обясняваме поведението на active-low LED-а.

led.value(LOGIC_ZERO_LEVEL)  # Подаваме логическа нула на изхода.
print("Подадохме логическа 0 към LED1.")  # Обясняваме какво направихме току-що.
time.sleep_ms(700)  # Изчакваме 700 ms, за да се види светването.

led.value(LOGIC_ONE_LEVEL)  # Подаваме логическа единица на изхода.
print("Подадохме логическа 1 към LED1.")  # Обясняваме втората стъпка.
time.sleep_ms(700)  # Изчакваме още 700 ms, за да се види изгасването.

for repeat_index in range(4):  # Правим още няколко цикъла, за да се затвърди идеята за цифров изход.
    led.low()  # Методът low() подава логическа нула на пина.
    print("Цикъл", repeat_index + 1, ": LED1 е в логическа 0.")  # Печатаме текущото състояние.
    time.sleep_ms(300)  # Изчакваме кратко, за да се види състоянието.
    led.high()  # Методът high() подава логическа единица на пина.
    print("Цикъл", repeat_index + 1, ": LED1 е в логическа 1.")  # Печатаме текущото състояние.
    time.sleep_ms(300)  # Изчакваме кратко и преди следващото повторение.

print("Примерът за цифров изход приключи.")  # Показваме финално съобщение.
