# Пример: NeoPixel smoke test с основни цветове и изгасване накрая.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: Този тест е удобен за първо включване, защото минава през няколко ясни цвята и после гаси модула.

from machine import Pin  # Импортираме Pin за power и data линиите.
import neopixel  # Импортираме neopixel драйвера за RGB модула.
import time  # Импортираме time за кратки видими паузи.

POWER_PIN = "P500"  # Избираме P500 като захранване на модула.
DATA_PIN = "P112"  # Избираме P112 като DIN линия на NeoPixel-а.
PIXEL_COUNT = 1  # Тестваме един пиксел.
HOLD_MS = 700  # Държим всеки тестов цвят 700 милисекунди.

vcc = Pin(POWER_PIN, Pin.OUT, value=1)  # Включваме захранването на външния NeoPixel.
np = neopixel.NeoPixel(Pin(DATA_PIN), PIXEL_COUNT)  # Създаваме драйверен обект за един пиксел.

test_colors = [  # Подготвяме кратка таблица за smoke test.
    ("red", (40, 0, 0)),  # Тестваме червения канал.
    ("green", (0, 40, 0)),  # Тестваме зеления канал.
    ("blue", (0, 0, 40)),  # Тестваме синия канал.
    ("white", (25, 25, 25)),  # Тестваме едновременно трите канала.
    ("off", (0, 0, 0)),  # Завършваме с изгасване.
]  # Завършваме списъка с тестови състояния.

print("=== NeoPixel smoke test ===")  # Печатаме заглавие на теста.
print("POWER =", POWER_PIN, "DATA =", DATA_PIN)  # Печатаме пиновете за проверка.

for name, color in test_colors:  # Обхождаме всички тестови цветове по ред.
    print("Set color:", name, color)  # Показваме текущото състояние в конзолата.
    np[0] = color  # Записваме новия цвят в буфера на пиксела.
    np.write()  # Изпращаме буфера към NeoPixel-а.
    time.sleep_ms(HOLD_MS)  # Изчакваме, за да бъде видим резултатът.

print("Smoke test приключи.")  # Печатаме финал на теста.
