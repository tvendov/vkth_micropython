# Пример: Базов I2C master в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: I2C(0) дели SCL пина си със SW1, затова в учебните примери по подразбиране ползваме I2C(1).

from machine import I2C  # Импортираме I2C за работа като master върху наличния хардуерен контролер.

i2c = I2C(1, freq=100000)  # Създаваме I2C(1) на 100 kHz върху бордовите пинове P100 и P101.

print("=== Базов I2C master ===")  # Печатаме заглавие на примера.
print("Обектът е", i2c)  # Печатаме обекта, за да видим канала, честотата и пиновете.

devices = i2c.scan()  # Сканираме шината за устройства с 7-битов адрес.
print("Намерени I2C адреси:", devices)  # Показваме списъка с намерените адреси.

if devices:  # Ако има поне едно устройство, показваме и първия адрес отделно.
    print("Първият намерен адрес е", hex(devices[0]))  # Печатаме първия намерен адрес в шестнадесетичен вид.
else:  # Ако няма намерени устройства, обясняваме защо това е нормално.
    print("Няма намерени устройства и това е нормално без свързан външен I2C модул.")  # Даваме нормално обяснение за празно сканиране.

print("Примерът за I2C master приключи.")  # Завършваме примера.
