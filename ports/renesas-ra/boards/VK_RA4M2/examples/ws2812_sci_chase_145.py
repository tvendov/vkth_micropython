# Пример: три движещи се цвята върху 1 + 12x12 = 145 WS2812 светодиода.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI инстанции = 3 броя -> SPI(0)=P103/P102/P100/P101, SPI(1)=P108/P111/P110/P109, SPI(2)=SCI2 simple SPI върху P111/P112/P113.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: P500 трябва да бъде включен, за да е активен WS2812 модулът в този setup.
# Бележка: При голяма матрица следете захранването да е достатъчно и масата да е обща с масата на борда.
# Бележка: Към борда свързвате data линията към DIN на първия LED, тук това е P112.

from machine import Pin  # Импортираме Pin, защото включваме P500 и подаваме data pin-а явно към драйвера.
from machine import WS2812  # Импортираме WS2812 драйвера с работещите дефолтни timing настройки.
import time  # Импортираме time за паузата между отделните стъпки на chase ефекта.

POWER_PIN = "P500"  # Използваме P500 като задължителен power-enable pin за модула в този setup.
DATA_PIN = "P112"  # Използваме P112 като data линия към първия светодиод.
LED_COUNT = 1 + 12 * 12  # Описваме точно 145 светодиода: 1 отделен плюс матрица 12x12.
STEP_DELAY_MS = 1000  # Преместваме тройката от цветове веднъж на секунда.

vcc = Pin(POWER_PIN, Pin.OUT, value=1)  # Включваме P500, защото без него модулът не стартира коректно в този setup.
time.sleep_ms(100)  # Изчакваме захранването и първият светодиод да се стабилизират.
strip = WS2812(pixel_count=LED_COUNT, pin=Pin(DATA_PIN), channels=3)  # Създаваме WS2812 обект за всички 145 светодиода.

colors = [  # Подготвяме трите цвята, които ще се гонят по лентата/матрицата.
    (255, 0, 0),  # Първата точка е червена.
    (0, 255, 0),  # Втората точка е зелена.
    (0, 0, 255),  # Третата точка е синя.
]  # Завършваме списъка с chase цветовете.

position = 0  # Започваме от първия светодиод.

print("=== WS2812 RGB chase over 145 LEDs ===")  # Печатаме заглавие на примера.
print("POWER =", POWER_PIN, "DATA =", DATA_PIN, "LED_COUNT =", LED_COUNT)  # Показваме основните параметри на примера.
print("P500 is enabled; keep the LED supply and board GND common.")  # Напомняме за правилното захранване.

try:  # Стартираме основния цикъл с чисто спиране при Ctrl+C.
    while True:  # Повтаряме chase ефекта непрекъснато.
        for i in range(LED_COUNT):  # Обхождаме всички светодиоди.
            strip[i] = (0, 0, 0)  # Гасим текущата рамка, за да останат само трите движещи се точки.

        for j in range(3):  # Поставяме последователно червената, зелената и синята точка.
            strip[(position + j) % LED_COUNT] = colors[j]  # Местим трите точки напред с wrap-around в края.

        strip.write()  # Изпращаме цялата рамка към матрицата.
        position = (position + 1) % LED_COUNT  # Преместваме шаблона с един светодиод напред.
        time.sleep_ms(STEP_DELAY_MS)  # Изчакваме 1 секунда преди следващата стъпка.
except KeyboardInterrupt:  # Ако примерът бъде спрян ръчно:
    for i in range(LED_COUNT):  # Обхождаме всички светодиоди за чисто изгасване.
        strip[i] = (0, 0, 0)  # Гасим всеки светодиод в буфера.
    strip.write()  # Прилагаме изгасения буфер върху матрицата.
    strip.deinit()  # Освобождаваме SCI backend-а и оставяме data линията ниска.
    print("WS2812 RGB chase example stopped cleanly.")  # Печатаме чист финал на примера.
