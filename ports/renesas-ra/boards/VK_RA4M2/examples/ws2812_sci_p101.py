# Пример: WS2812 през machine.WS2812 върху P101 като алтернативен SCI0 TX/MOSI pin.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI инстанции = 3 броя -> SPI(0)=P103/P102/P100/P101, SPI(1)=P108/P111/P110/P109, SPI(2)=SCI2 simple SPI върху P111/P112/P113.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: Този пример показва, че machine.WS2812 вече работи и върху алтернативен SCI TX/MOSI pin, не само върху P112.
# Бележка: P101 съвпада с I2C(1).SDA и SPI(0).MOSI, така че не активирайте тези интерфейси едновременно с този пример.

from machine import Pin  # Импортираме Pin за захранващия GPIO и за избора на data pin.
from machine import WS2812  # Импортираме новия WS2812 драйвер, който намира SCI канала по подадения pin.
import time  # Импортираме time за видими паузи между цветовете.

POWER_PIN = "P500"  # Използваме P500 като малко захранване за единичен външен модул.
DATA_PIN = "P101"  # Използваме P101 като алтернативен data pin от SCI0 групата.
PIXEL_COUNT = 1  # Тук демонстрираме един пиксел за най-прост и безопасен старт.
STEP_DELAY_MS = 500  # Държим всеки цвят половин секунда, за да се вижда ясно.

vcc = Pin(POWER_PIN, Pin.OUT, value=1)  # Включваме захранването към външния модул.
strip = WS2812(pixel_count=PIXEL_COUNT, pin=Pin(DATA_PIN), channels=3)  # Създаваме WS2812 обекта върху P101.

colors = [  # Подготвяме кратка цветова дъга с умерена яркост.
    (40, 0, 0),  # Червено.
    (0, 40, 0),  # Зелено.
    (0, 0, 40),  # Синьо.
    (40, 20, 0),  # Оранжево.
    (20, 0, 40),  # Виолетово.
]  # Завършваме таблицата с демонстрационни цветове.

print("=== WS2812 over alternate SCI pin ===")  # Печатаме заглавие на примера.
print("POWER =", POWER_PIN, "DATA =", DATA_PIN, "PIXELS =", PIXEL_COUNT)  # Показваме използваните пинове и броя пиксели.

try:  # Стартираме безкраен цикъл с чисто спиране при Ctrl+C.
    while True:  # Повтаряме цветната последователност непрекъснато.
        for color in colors:  # Обхождаме всички цветове по ред.
            strip[0] = color  # Записваме новия цвят в буфера на първия пиксел.
            strip.write()  # Изпращаме кодираната последователност към избрания SCI TX/MOSI pin.
            time.sleep_ms(STEP_DELAY_MS)  # Изчакваме, за да остане цветът видим.
except KeyboardInterrupt:  # Ако примерът бъде спрян ръчно:
    strip.fill((0, 0, 0))  # Гасим всички пиксели в буфера.
    strip.write()  # Прилагаме буфера върху реалния модул.
    strip.deinit()  # Освобождаваме SCI backend-а и оставяме линията ниска.
    print("WS2812 примерът върху P101 беше спрян и пикселът е изгасен.")  # Печатаме чист финал.
