# Пример: Базова UART комуникация на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.

from machine import UART  # Импортираме UART класа за серийна комуникация.
import time  # Импортираме time за кратко закъснение.

# --- Налични UART канали на VK_RA4M2 ---
# UART(0) -> TX=P411, RX=P410
# UART(2) -> TX=P302, RX=P301
# UART(7) -> TX=P401, RX=P402, CTS=P403
# UART(9) -> TX=P602, RX=P601, CTS=P603

# Забележка: UART(7) използва P401, който е и SDA на I2C(0).
# Забележка: UART(0) използва P411/P410, които са и TouchPad пинове.

# --- Създаване на UART инстанция ---
uart = UART(9, 115200)  # Създаваме UART(9) на 115200 baud (TX=P602, RX=P601).

print("=== Базова UART комуникация ===")  # Печатаме заглавие.
print("UART канал:", uart)  # Показваме информация за UART обекта.

# --- Изпращане на данни ---
message = "Здравей от VK_RA4M2!\r\n"  # Подготвяме съобщение за изпращане.
bytes_sent = uart.write(message)  # Изпращаме съобщението по TX пина.
print("Изпратени байтове:", bytes_sent)  # Показваме колко байта са изпратени.

# --- Четене на данни ---
time.sleep_ms(100)  # Кратко закъснение, за да пристигнат данни (ако има loopback).

available = uart.any()  # Проверяваме дали има налични байтове за четене.
print("Налични байтове за четене:", available)  # Показваме броя.

if available > 0:  # Ако има данни за четене:
    received = uart.read(available)  # Четем наличните байтове от RX буфера.
    print("Получено:", received)  # Показваме получените данни.
else:  # Ако няма данни:
    print("Няма получени данни (свържете TX към RX за loopback тест).")  # Обясняваме защо.

# --- Допълнителни UART настройки ---
print()  # Празен ред за четимост.
print("--- UART с различни параметри ---")  # Подзаглавие.

uart2 = UART(9, 9600)  # Пресъздаваме UART(9) на 9600 baud.
print("UART 9600 baud:", uart2)  # Показваме новите настройки.

uart2.write(b"\x01\x02\x03")  # Изпращаме сурови байтове.
print("Изпратени 3 сурови байта.")  # Потвърждаваме.

# --- Примерен loopback тест ---
print()  # Празен ред за четимост.
print("--- Loopback тест (ако TX е свързан към RX) ---")  # Подзаглавие.

uart_loop = UART(9, 115200)  # Създаваме UART(9) за loopback тест.
test_data = b"ABCD1234"  # Тестови данни за изпращане.
uart_loop.write(test_data)  # Изпращаме данните.
time.sleep_ms(50)  # Чакаме данните да се върнат.

loopback_data = uart_loop.read(len(test_data))  # Четем обратно получените данни.

if loopback_data == test_data:  # Сравняваме изпратеното с получеността.
    print("Loopback УСПЕХ:", loopback_data)  # Данните съвпадат.
elif loopback_data is not None:  # Получили сме нещо, но не съвпада.
    print("Loopback ЧАСТИЧЕН:", loopback_data)  # Показваме какво сме получили.
else:  # Нищо не е получено.
    print("Loopback НЕУСПЕХ: няма данни. Свържете TX(P602) към RX(P601).")  # Указание за свързване.

print()  # Празен ред за четимост.
print("Примерът за UART приключи.")  # Завършваме примера.

