# Пример: WS2812 smoke test през machine.WS2812 върху P112.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI инстанции = 3 броя -> SPI(0)=P103/P102/P100/P101, SPI(1)=P108/P111/P110/P109, SPI(2)=SCI2 simple SPI върху P111/P112/P113.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: Този тест е подходящ за първа проверка дали P112 и новият C драйвер дават стабилен WS2812 сигнал.
# Бележка: P500 трябва да бъде включен задължително, за да е активен WS2812 модулът в този setup.
# Бележка: Ако има отделно основно захранване, масата му трябва да е обща с масата на борда.

from machine import Pin  # Импортираме Pin за задължителния power-enable pin на модула.
from machine import WS2812  # Импортираме WS2812 драйвера с TX-only SCI2 backend.
import time  # Импортираме time за кратки видими паузи между тестовите цветове.

POWER_PIN = "P500"  # Използваме P500 като задължителен power-enable pin за WS2812 модула.
DATA_PIN = "P112"  # Използваме P112 като DIN линия към модула.
PIXEL_COUNT = 1  # Тестът е за един пиксел.
HOLD_MS = 700  # Държим всеки тестов цвят 700 милисекунди.

vcc = Pin(POWER_PIN, Pin.OUT, value=1)  # Включваме P500, защото без него модулът не стартира коректно в този setup.
time.sleep_ms(100)  # Изчакваме power-enable линията и модулът да се стабилизират.
strip = WS2812(pixel_count=PIXEL_COUNT, pin=Pin(DATA_PIN), channels=3)  # Създаваме обект с дефолтните timing настройки.

test_colors = [  # Подготвяме кратка последователност за smoke test.
    ("red", (40, 0, 0)),  # Проверяваме червения канал.
    ("green", (0, 40, 0)),  # Проверяваме зеления канал.
    ("blue", (0, 0, 40)),  # Проверяваме синия канал.
    ("white", (20, 20, 20)),  # Проверяваме едновременно трите канала.
    ("off", (0, 0, 0)),  # Завършваме с изгасване.
]  # Завършваме списъка със състояния за теста.

print("=== WS2812 smoke test ===")  # Печатаме заглавие на теста.
print("POWER =", POWER_PIN, "DATA =", DATA_PIN)  # Показваме основните пинове.
print("P500 is mandatory in this setup.")  # Напомняме, че P500 трябва да е включен.

for name, color in test_colors:  # Обхождаме всички тестови цветове.
    print("Set color:", name, color)  # Печатаме текущото състояние в конзолата.
    strip[0] = color  # Записваме цвета в буфера на първия пиксел.
    strip.write()  # Изпращаме буфера към WS2812 модула през P112.
    time.sleep_ms(HOLD_MS)  # Изчакваме, за да остане резултатът видим.

strip.deinit()  # Освобождаваме SCI2 backend-а след края на теста.
print("WS2812 smoke test приключи.")  # Печатаме финал на теста.
