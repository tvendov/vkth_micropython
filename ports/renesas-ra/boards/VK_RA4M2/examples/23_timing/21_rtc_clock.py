# STEMKIDS: часовник с RTC на VK_RA4M2.
# Необходими са кварц 32.768 kHz и съвместим MicroPython фърмуер.
from machine import RTC, mem8, mem16  # Достъп до RTC и хардуерни регистри с размер 8 и 16 бита.
import time  # Импортираме изчакването между прочитанията.

BACKUP_SIZE = 128  # RA4M2 има 128 байта памет за данни, запазвани чрез VBATT.
BACKUP_BASE = 0x4001E500  # Начален адрес на тези байтове; последният е на 0x4001E57F.
BACKUP_ENABLE = 0x4001E4C0  # Адрес на регистъра за разрешаване на достъпа до тях.
REGISTER_PROTECT = 0x4001E3FE  # Адрес на регистъра за защита от запис PRCR.

rtc = RTC()  # Отваряме часовника, без да презаписваме датата и часа.


def set_clock(year, month, day, weekday, hour, minute, second):  # Извиква се ръчно за сверяване; 0=неделя, 1=понеделник, ..., 6=събота.
    clock = RTC(source="sosc")  # Избираме кварца 32.768 kHz чрез разширението на VK RA порта.
    clock.datetime((year, month, day, weekday, hour, minute, second, 0))  # Записваме дата и час; подсекундите не се поддържат и подаваме 0.


def read_clock():  # Функция за четене и показване на часовника.
    dt = rtc.datetime()  # Прочитаме датата и часа от RTC.
    print("%04d-%02d-%02d %02d:%02d:%02d" % (dt[0], dt[1], dt[2], dt[4], dt[5], dt[6]))  # Печатаме дата и час.


def backup_write_byte(index, value):  # Записва един байт само при изрично извикване.
    if index < 0 or index >= BACKUP_SIZE:  # Допустимите номера са от 0 до 127.
        raise ValueError("Backup index must be 0..127")  # Отхвърляме номер извън тази област.
    if value < 0 or value > 255:  # Един байт съдържа стойност от 0 до 255.
        raise ValueError("Backup value must be 0..255")  # Отхвърляме стойност извън този диапазон.
    protect = mem16[REGISTER_PROTECT] & 0x000F  # Запомняме текущите разрешения за запис.
    mem16[REGISTER_PROTECT] = 0xA500 | protect | 0x0002  # Ключът 0xA5 и битът PRC1 разрешават необходимите записи.
    try:  # След операцията винаги ще затворим достъпа.
        mem8[BACKUP_ENABLE] = 0x08  # Отваряме достъпа чрез бит VBAE=1.
        time.sleep_us(1)  # Изчакваме повече от изискваните 500 ns преди достъп.
        mem8[BACKUP_BASE + index] = value  # Записваме байта на избраното място.
    finally:  # Изпълнява се и ако операцията предизвика грешка.
        mem8[BACKUP_ENABLE] = 0x00  # Затваряме достъпа чрез VBAE=0, за да се пазят данните при работа от батерия.
        time.sleep_us(1)  # Осигуряваме повече от 250 ns преди евентуално преминаване в дълбок сън.
        mem16[REGISTER_PROTECT] = 0xA500 | protect  # Възстановяваме предишните разрешения за запис.


def backup_read_byte(index):  # Прочита един байт, без да променя неговата стойност.
    if index < 0 or index >= BACKUP_SIZE:  # Допустимите номера са от 0 до 127.
        raise ValueError("Backup index must be 0..127")  # Отхвърляме номер извън тази област.
    protect = mem16[REGISTER_PROTECT] & 0x000F  # Запомняме текущите разрешения за запис.
    mem16[REGISTER_PROTECT] = 0xA500 | protect | 0x0002  # Разрешаваме управлението на достъпа чрез PRC1.
    try:  # След операцията винаги ще затворим достъпа.
        mem8[BACKUP_ENABLE] = 0x08  # Отваряме достъпа чрез бит VBAE=1.
        time.sleep_us(1)  # Изчакваме повече от 500 ns преди прочитането.
        value = mem8[BACKUP_BASE + index]  # Прочитаме стойността на избрания байт.
    finally:  # Изпълнява се и ако операцията предизвика грешка.
        mem8[BACKUP_ENABLE] = 0x00  # И след четене затваряме достъпа, за да се пазят данните при работа от батерия.
        time.sleep_us(1)  # Изчакваме повече от 250 ns преди евентуално преминаване в дълбок сън.
        mem16[REGISTER_PROTECT] = 0xA500 | protect  # Възстановяваме предишните разрешения за запис.
    return value  # Връщаме прочетената стойност.


def main():  # Главна функция на програмата.
    backup_read_byte(0)  # След reset затваряме достъпа чрез прочит без промяна на данните; VBAE се връща в 1 при reset.
    while True:  # Повтаряме до натискане на Ctrl+C.
        read_clock()  # Прочитаме и показваме хардуерния час.
        time.sleep(1)  # Добавяме пауза 1 секунда към времето за четене и печат; RTC брои самостоятелно.


if __name__ == "__main__":  # При импорт оставяме функциите достъпни без автоматичен цикъл.
    main()  # При стартиране само четем и показваме запазения час, без сверяване.
