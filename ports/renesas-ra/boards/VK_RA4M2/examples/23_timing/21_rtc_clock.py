# STEMKIDS: часовник с RTC на VK платка с Renesas RA.
# Необходими са кварц 32.768 kHz и съвместим MicroPython фърмуер.
from machine import RTC  # Импортираме хардуерния часовник.
import time  # Импортираме изчакването между прочитанията.

SET_TIME = 0  # 1 = еднократно сверяване при стартиране; 0 = запазваме часа.
YEAR = 2026  # Примерна година; преди сверяване въведи актуалната.
MONTH = 10  # Месец от 1 до 12.
DAY = 19  # Ден от месеца.
WEEKDAY = 1  # За този RA порт: 0=неделя, 1=понеделник, ..., 6=събота.
HOUR = 12  # Час от 0 до 23; примерната стойност не е текущият час.
MINUTE = 0  # Минута от 0 до 59.
SECOND = 0  # Секунда от 0 до 59.

rtc = RTC()  # Отваряме часовника, без да презаписваме датата и часа.


def set_clock(year, month, day, weekday, hour, minute, second):  # Функция за сверяване.
    clock = RTC(source="sosc")  # Избираме кварца 32.768 kHz чрез разширението на VK RA порта.
    clock.datetime((year, month, day, weekday, hour, minute, second, 0))  # Записваме датата и часа; последното поле е 0.


def read_clock():  # Функция за четене и показване на часовника.
    dt = rtc.datetime()  # Прочитаме датата и часа от RTC.
    print("%04d-%02d-%02d %02d:%02d:%02d" % (dt[0], dt[1], dt[2], dt[4], dt[5], dt[6]))  # Печатаме дата и час.


def main():  # Главна функция на програмата.
    if SET_TIME == 1:  # Сверяваме само когато потребителят е разрешил това.
        set_clock(YEAR, MONTH, DAY, WEEKDAY, HOUR, MINUTE, SECOND)  # Подаваме стойностите за сверяване.
    while True:  # Повтаряме до натискане на Ctrl+C.
        read_clock()  # Прочитаме и показваме хардуерния час.
        time.sleep(1)  # Изчакваме една секунда; самото време се отчита от RTC.


if __name__ == "__main__":  # При импорт оставяме функциите достъпни без автоматичен цикъл.
    main()  # При пряко стартиране изпълняваме програмата.
