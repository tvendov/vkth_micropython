from machine import RTC  # Достъп до хардуерния часовник.
import time  # Достъп до изчакването.

SET_TIME = 0  # 1 = сверяване при стартиране; 0 = само четене на запазения час.
rtc = RTC()  # Отваряме RTC, без да променяме запазения час.

def set_clock(year, month, day, weekday, hour, minute, second):  # Сверява RTC; денят от седмицата е 1 за понеделник до 7 за неделя.
    clock = RTC(source="sosc")  # Избираме външния кварц 32.768 kHz.
    clock.datetime((year, month, day, weekday, hour, minute, second, 0))  # Записваме подадените дата и час в RTC.


def read_clock():  # Чете RTC и отпечатва текущите дата и час.
    dt = rtc.datetime()  # Прочитаме датата и часа от RTC.
    print("%04d-%02d-%02d %02d:%02d:%02d" % (dt[0], dt[1], dt[2], dt[4], dt[5], dt[6]))  # Показваме година-месец-ден час:минута:секунда.


def main():  # Главна функция на програмата.
    if SET_TIME == 1:  # Сверяваме само когато изрично сме задали 1.
        set_clock(2026, 10, 19, 1, 22, 0, 0)  # Примерни стойности; замени с актуалните година, месец, ден, ден от седмицата, час, минута и секунда.
    while True:  # Четем непрекъснато до Ctrl+C.
        read_clock()  # Прочитаме и показваме часа.
        time.sleep(1)  # Изчакваме една секунда преди следващото четене.


if __name__ == "__main__":  # Стартираме програмата само при пряко изпълнение на файла.
    main()  # Извикваме главната функция.
