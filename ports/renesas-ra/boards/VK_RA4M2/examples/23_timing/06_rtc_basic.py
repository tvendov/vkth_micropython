# Пример: Основи на RTC в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: По подразбиране този пример само чете RTC и не променя датата и часа, за да не бърка настройките на платката.

from machine import RTC  # Импортираме RTC, за да работим с часовника в реално време.

rtc = RTC()  # Създаваме обект за достъп до вградения RTC модул.
SET_DEMO_TIME = False  # Тази константа пази примера безопасен, защото по подразбиране не променя часовника.

print("=== RTC basics ===")  # Печатаме заглавие на примера.
print("RTC info =", rtc.info())  # Печатаме диагностичната информация за стартиране на RTC.
print("RTC calibration =", rtc.calibration())  # Печатаме текущата калибрационна стойност.

current_datetime = rtc.datetime()  # Четем текущата дата и час като осемелементен tuple.
print("Текущ RTC tuple =", current_datetime)  # Показваме точно как изглежда tuple-ът върнат от rtc.datetime().
print("Форматът е (година, месец, ден, weekday, час, минута, секунда, subseconds).")  # Обясняваме подредбата на полетата за начинаещи.

if SET_DEMO_TIME:  # Само ако потребителят умишлено разреши, ще задаваме нова дата и час.
    rtc.datetime((2026, 3, 6, 5, 12, 0, 0, 0))  # Това е примерна стойност за демонстрация на set операцията.
    print("RTC беше настроен на демонстрационна стойност.")  # Потвърждаваме, че е направена промяна.
else:  # В нормалния случай само обясняваме какво би се случило.
    print("SET_DEMO_TIME е False и RTC не се променя.")  # Печатаме безопасно съобщение.

print("Примерът за RTC приключи.")  # Завършваме примера.
