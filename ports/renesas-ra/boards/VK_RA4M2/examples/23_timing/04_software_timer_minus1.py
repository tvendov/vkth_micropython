# Пример: Софтуерен Timer(-1) в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 2 броя -> Timer(1), Timer(2), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: Този пример пробва два често срещани стила за инициализация на Timer(-1), за да остане полезен при различни firmware конфигурации.

from machine import Pin, Timer  # Импортираме Pin и Timer за демонстрацията на софтуерния таймер.
import time  # Импортираме time, за да оставим таймера да работи кратко време.

led = Pin("LED1", Pin.OUT)  # Вземаме LED1 като видим индикатор за сработване на callback-а.
soft_timer = Timer(-1)  # Създаваме софтуерен таймер чрез идентификатор -1.
soft_state = {"count": 0}  # Пазим броя сработвания в mutable структура.
started = False  # С този флаг ще следим дали таймерът е стартирал успешно.


def soft_timer_callback(timer_object):  # Това е функцията, която ще се извиква при всяко сработване на софтуерния таймер.
    soft_state["count"] = soft_state["count"] + 1  # Увеличаваме брояча при всяко събитие.
    led.value(0 if led.value() else 1)  # Превключваме LED, за да виждаме че callback-ът се изпълнява.


print("=== Софтуерен Timer(-1) ===")  # Печатаме заглавие на примера.

try:  # Първо пробваме по-често срещания API стил с период в милисекунди.
    if hasattr(Timer, "PERIODIC"):  # Проверяваме дали класът Timer предлага константа за периодичен режим.
        soft_timer.init(period=250, mode=Timer.PERIODIC, callback=soft_timer_callback)  # Стартираме Timer(-1) с 250 ms период.
        started = True  # Отбелязваме, че таймерът е стартирал.
        print("Timer(-1) тръгна с period/mode API.")  # Показваме кой стил е бил приет.
except Exception as first_error:  # Ако първият стил не е приет, минаваме към резервен вариант.
    print("period/mode API не тръгна:", first_error)  # Печатаме причината първият опит да не е успешен.

if not started:  # Ако още не сме стартирали таймера, пробваме втория стил с честота.
    try:  # Влизаме в защитен блок за втория опит.
        soft_timer.init(freq=4, callback=soft_timer_callback, hard=False)  # Пробваме инициализация с честота 4 Hz.
        started = True  # Отбелязваме, че вторият стил е успял.
        print("Timer(-1) тръгна с freq API.")  # Печатаме кой резервен стил е сработил.
    except Exception as second_error:  # Ако и вторият стил не тръгне, само информираме потребителя.
        print("freq API също не тръгна:", second_error)  # Показваме причината и за втория неуспех.

if started:  # Само ако таймерът е тръгнал, чакаме да видим няколко callback събития.
    time.sleep_ms(1200)  # Оставяме таймера да работи около 1.2 секунди.
    soft_timer.deinit()  # Спираме софтуерния таймер, за да приключим чисто примера.
    print("Броят сработвания е", soft_state["count"])  # Печатаме колко callback извиквания е имало.
else:  # Ако нито един стил не е тръгнал, приключваме с диагностично съобщение.
    print("Timer(-1) не беше стартиран в този runtime.")  # Даваме ясно съобщение, че тази среда не е приела инициализацията.

led.off()  # Оставяме LED изключен след края на примера.

print("Примерът за Timer(-1) приключи.")  # Завършваме примера.
