# Пример: Дебаунс на бутон в MicroPython на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Бележка: При SW1 логическа 0 означава натиснат бутон, а логическа 1 означава отпуснат бутон.

from machine import Pin  # Импортираме Pin за работа с бутона и LED.
import time  # Импортираме time за polling и измерване на времето за дебаунс.
import uasyncio as asyncio  # Импортираме uasyncio за асинхронния вариант на дебаунс.

button = Pin("SW1", Pin.IN, Pin.PULL_UP)  # Настройваме SW1 като вход с pull-up резистор.
led = Pin("LED1", Pin.OUT)  # Вземаме LED1, за да показваме валидно натискане.

last_stable_value = 1  # Започваме с предположението, че бутонът е отпуснат.
last_change_ms = time.ticks_ms()  # Запомняме момента на последната промяна.
accepted_presses = 0  # Пазим броя на валидните натискания след дебаунс.

print("=== Дебаунс с polling ===")  # Печатаме заглавие на блокиращия вариант.

poll_start_ms = time.ticks_ms()  # Запомняме началото на наблюдението.

while time.ticks_diff(time.ticks_ms(), poll_start_ms) < 5000:  # Наблюдаваме бутона в продължение на 5 секунди.
    current_value = button.value()  # Четем моментната логическа стойност на входа.
    if current_value != last_stable_value:  # Проверяваме дали е настъпила промяна спрямо последното стабилно състояние.
        now_ms = time.ticks_ms()  # Вземаме текущото време само при промяна.
        if time.ticks_diff(now_ms, last_change_ms) >= 40:  # Приемаме промяната за валидна само ако е минало поне 40 ms.
            last_change_ms = now_ms  # Обновяваме момента на последната приета промяна.
            last_stable_value = current_value  # Приемаме новата стойност за стабилна.
            if last_stable_value == 0:  # Ако новото стабилно състояние е 0, значи бутонът е натиснат.
                accepted_presses = accepted_presses + 1  # Увеличаваме броя на валидните натискания.
                led.value(0 if led.value() else 1)  # Превключваме LED при валидно натискане.
                print("Валидно натискане номер", accepted_presses)  # Печатаме броя на приетите натискания.
    time.sleep_ms(5)  # Изчакваме кратко, за да не въртим процесора излишно бързо.

print("=== Дебаунс с asyncio ===")  # Печатаме заглавие за асинхронния вариант.


async def debounce_task():  # Дефинираме асинхронна задача за debounce логиката.
    stable_value = button.value()  # Започваме от текущото стабилно състояние на бутона.
    stable_count = 0  # Броим колко поредни проби са еднакви.
    async_presses = 0  # Пазим отделен брояч за асинхронния вариант.
    for sample_index in range(80):  # Правим краен брой проби, за да остане примерът кратък.
        sample_value = button.value()  # Четем поредната проба от бутона.
        if sample_value == stable_value:  # Ако пробата е същата като стабилната стойност, увеличаваме брояча.
            stable_count = stable_count + 1  # Увеличаваме броя на еднаквите поредни проби.
        else:  # Ако пробата е различна, започваме ново кандидат-стабилно състояние.
            stable_value = sample_value  # Приемаме новата стойност за кандидат.
            stable_count = 1  # Започваме броенето отначало.
        if stable_value == 0 and stable_count == 4:  # Ако видим четири поредни проби с 0, приемаме валидно натискане.
            async_presses = async_presses + 1  # Увеличаваме броя на валидните асинхронни натискания.
            print("Async валидно натискане номер", async_presses)  # Печатаме поредния номер на валидното натискане.
        await asyncio.sleep_ms(10)  # Отстъпваме управление за 10 ms без блокиране.


asyncio.run(debounce_task())  # Стартираме асинхронната debounce задача.
led.off()  # Оставяме LED изключен след края на примера.

print("Валидни натискания в polling частта:", accepted_presses)  # Печатаме колко натискания са приети в първата част.
print("Примерът за дебаунс приключи.")  # Завършваме примера.
