# Пример: Аналогов вход с ADC на VK_RA4M2.
# Ресурси на VK_RA4M2: ADC външни входове = 13 броя -> P000, P001, P002, P003, P004, P005, P006, P007, P008, P013, P014, P015, P500.
# Ресурси на VK_RA4M2: ADC вътрешни източници = 3 броя -> ADC.CORE_TEMP, ADC.CORE_VREF, ADC.VREF.
# Ресурси на VK_RA4M2: DAC изходи = 2 броя -> P014, P015.
# Ресурси на VK_RA4M2: PWM изходи = 14 броя -> P107, P106, P105, P104, P113, P114, P112, P115, P608, P409, P408, P600, P304, P303.
# Ресурси на VK_RA4M2: UART инстанции = 4 броя -> UART(0), UART(2), UART(7), UART(9).
# Ресурси на VK_RA4M2: I2C master = 2 броя -> I2C(0)=P400/P401 и I2C(1)=P100/P101.
# Ресурси на VK_RA4M2: I2CTarget = 2 броя -> I2CTarget(0)=P400/P401 и I2CTarget(1)=P100/P101.
# Ресурси на VK_RA4M2: SPI канали = 1 брой -> SPI=P103/P102/P100/P101.
# Ресурси на VK_RA4M2: TouchPad входове = 12 броя -> P205, P206, P407, P408, P409, P410, P411, P412, P413, P414, P415, P708.
# Ресурси на VK_RA4M2: LED = 1 брой -> LED1=P204, бутон = 1 брой -> SW1=P400.
# Ресурси на VK_RA4M2: Хардуерни Timer = 6 броя -> Timer(1), Timer(2), Timer(3), Timer(4), Timer(5), Timer(6), софтуерен Timer = Timer(-1), RTC = 1 брой, Data Flash = 8 KB, /flash = около 94 KB.
# Обяснение: ADC е аналогово-цифров преобразувател, който превръща непрекъснато напрежение в цифрово число.
# Обяснение: За стабилна демонстрация тук четем вътрешните канали за температура и опорно напрежение, а не плаващ външен пин.

from machine import ADC  # Импортираме класа ADC, чрез който се четат аналоговите канали.
import time  # Импортираме time, за да четем периодично и да виждаме промяната във времето.

EXTERNAL_ADC_PINS = ("P000", "P001", "P002", "P003", "P004", "P005", "P006", "P007", "P008", "P013", "P014", "P015", "P500")  # Записваме всички външни ADC пинове в една таблица.

temperature_adc = ADC(ADC.CORE_TEMP)  # Създаваме ADC обект за вътрешния температурен канал.
vref_adc = ADC(ADC.CORE_VREF)  # Създаваме ADC обект за вътрешното опорно напрежение.

print("=== Аналогов вход с ADC ===")  # Печатаме заглавие на примера.
print("Външни ADC пинове:", EXTERNAL_ADC_PINS)  # Показваме списъка с валидните външни ADC пинове.
print("Ще четем вътрешните канали CORE_TEMP и CORE_VREF.")  # Обясняваме избрания безопасен демонстрационен подход.

for sample_index in range(10):  # Правим 10 последователни измервания.
    temp_raw = temperature_adc.read()  # Четем суровата ADC стойност на вътрешния температурен канал.
    temp_u16 = temperature_adc.read_u16()  # Четем същия канал, но скалиран до 16-битов диапазон.
    vref_raw = vref_adc.read()  # Четем суровата ADC стойност на вътрешното опорно напрежение.
    vref_u16 = vref_adc.read_u16()  # Четем същия канал, но скалиран до 16-битов диапазон.
    print("Проба", sample_index + 1, "TEMP raw =", temp_raw, "TEMP u16 =", temp_u16, "VREF raw =", vref_raw, "VREF u16 =", vref_u16)  # Печатаме и четирите резултата на един ред.
    time.sleep_ms(300)  # Чакаме 300 ms между измерванията.

print("Примерът за ADC приключи.")  # Показваме финално съобщение.
